"""3-level measured-equivalence gate: TitaNet ONNX engine vs the CUDA reference.

This is the parity harness that decides whether ``titanet-large-v1`` survives
onto non-NVIDIA backends (plan decision #3; policy in docs/gpu-contracts.md):

* **Mel level** — ``services/titanet/app/mel.py`` output vs the NeMo
  ``AudioToMelSpectrogramPreprocessor`` on identical post-preprocess audio
  (``references/mel/``, generated by ``tools/generate_mel_references.py``).
  Isolates the reimplemented front-end from preprocess-dependency skew.
* **Vector level** — the full ONNX engine chain on the golden corpus vs the
  committed CUDA service references (``references/cuda/embed.json``):
  identical ``skip_reason`` per window, ``snr_db`` within ±0.5 dB, per-window
  cosine ≥ the ratcheted floor.
* **Decision level** — replay the labeled same/different-speaker pairs
  (``corpus/embed-pairs.json``) through voxint's actual matching gates
  (``match_min_cosine`` 0.60 / ``grounded_min_cosine`` 0.70): no pair may
  cross either gate differently than the CUDA embeddings; pair-cosine drift
  and top-1/top-2 structure must stay inside the ratcheted bounds.

Tolerances were MEASURED first (2026-08-13, maintainer amd64 workstation, onnxruntime CPU EP on
amd64) and then ratcheted with margin — see docs/gpu-contracts.md for the
recorded numbers. Loosening any of them is a space-id decision, not a test fix.

Prerequisites (each missing one is an explicit SKIP in dev runs):
``uv sync --extra parity``; the exported graph at
``services/titanet/models/titanet-large.onnx`` (tools/export_titanet_onnx.py);
the committed mel/CUDA references. Release/CI runs set
``VOXINT_PARITY_REQUIRED=1``, which turns any missing prerequisite into a
hard failure so a fully-skipped suite can never green-board a release.
"""

