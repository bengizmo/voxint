# --- vs the 0.3.0 CUDA references; recorded in docs/gpu-contracts.md):
# --- mel worst 2.2e-4 · vector cosine min 0.9999966 / p50 0.9999993 ·
# --- snr diff 0.0 · pair drift max 4.6e-4 · gate crossings 0 · top1 flips 0 ·
# --- margin drift max 3.5e-4. Bounds below carry ~5-100x margin for arm64
# --- SIMD/BLAS variance (arm64 to be measured when Phase 2 CI lands).
MEL_MAX_ABS_DIFF = 1e-3  # normalized log-mel units (measured worst 2.2e-4)
VECTOR_MIN_COSINE = 0.9995  # per embedded window (measured min 0.9999966)
SNR_TOLERANCE_DB = 0.5  # measured: exact agreement
PAIR_COSINE_MAX_DRIFT = 2e-3  # per labeled pair (measured max 4.6e-4)
TOP1_MARGIN_MAX_DRIFT = 2e-3  # (measured max 3.5e-4)
MATCHING_GATES = (0.60, 0.70)  # match_min_cosine / grounded_min_cosine

# Release/CI gate mode: with VOXINT_PARITY_REQUIRED=1 every missing
