def language_label(code: str) -> str:
    """Human display label for a whisper language code: "Spanish (es)".

    An unknown code (a future model emitting something the map predates)
    renders as the raw code — honest, never a guessed name.
    """
    name = LANGUAGE_NAMES.get(code)
    return f"{name} ({code})" if name else code
